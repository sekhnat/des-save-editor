#!/usr/bin/env python3
"""Write the recovered field table from des_fields.py into the offline HTML editor.

des_fields.py is the single source; the page's DEFS and LAYOUT are generated.
Use --stdout to emit only the replacement script block, and --check to fail
when the page is out of date (useful in tests and build tools).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE / 'src'))
import des_fields  # noqa: E402

START = '/* FIELDS:START (generated by tools/embed_fields.py; edit des_fields.py) */'
END = '/* FIELDS:END */'


def _js(value) -> str:
    # Escaping < prevents a description from terminating the inline script.
    return (json.dumps(value, ensure_ascii=False, separators=(',', ':'))
            .replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029'))


def fields_block() -> str:
    defs = [[m['name'], m['kind'], m['label'], m['lo'], m['hi'], m['help']]
            for m in des_fields.FIELDS.values()]
    layout = [[title, names] for title, names in des_fields.LAYOUT.items()]
    families = [[template, last] for template, last in des_fields.FAMILIES]
    return (START + '\nconst DEFS = [\n' + ',\n'.join('  ' + _js(row) for row in defs)
            + '\n];\nconst LAYOUT = [\n' + ',\n'.join('  ' + _js(row) for row in layout)
            + '\n];\nconst FAMILIES = [\n' + ',\n'.join('  ' + _js(row) for row in families)
            + '\n];\nconst WORLD_NAMES = ' + _js(des_fields.WORLD_NAMES) + ';\n' + END)


def embed(html: str) -> str:
    if html.count(START) != 1 or html.count(END) != 1:
        raise ValueError('Could not locate one FIELDS block')
    start, end = html.index(START), html.index(END) + len(END)
    return html[:start] + fields_block() + html[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--html', type=Path, default=HERE / 'des_editor.html')
    parser.add_argument('--stdout', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.stdout:
        sys.stdout.write(fields_block() + '\n')
        return 0
    html = args.html.read_text(encoding='utf-8')
    updated = embed(html)
    if args.check:
        if updated != html:
            print('des_editor.html field table is out of date; run tools/embed_fields.py',
                  file=sys.stderr)
            return 1
        return 0
    args.html.write_text(updated, encoding='utf-8')
    print(f'Embedded {len(des_fields.FIELDS)} fields in {len(des_fields.LAYOUT)} groups',
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
