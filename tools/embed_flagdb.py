#!/usr/bin/env python3
"""Embed the event-flag database (flagdb.json) into the offline HTML editor.

The page's Events tab needs the bosses, the NPC state machines and a label for
every documented flag. Labels are computed here with des_flags.FlagDB, so the
page and the CLI describe a flag with the same words:

    FLAGDB = {
      ranges: [[first, end, bank key, bits per area]],   // the local ranges
      areas: 8, backup,
      areaNames: ["m01 Nexus", ...],
      bosses: [[id, area, name, world, soul, [block flags], [room flags]]],
      npcs: [[list, name, [[id, STATE_CONSTANT, label, marker]], about, where]],
      forgive: [[list, hostile state id, [[area, flag], ...]]],  // SeekForgiveness
      local: [[[id, label, kind], ...] per area],  // kind: "p" pickup, "u" usage
                                                   // (dimmed), "" other
      scripts: [[id, label]],                    // local ids named only by
      localAny: [[id, label]],                   // non-map scripts or talk
                                                 // tables (fallbacks)
      global: [[id, label]],
      pickups: [[[flag, level, [[cat, item id, count, name], ...]], ...] per area],
                                                 // cat: W, A, R or G (the page's
                                                 // item categories)
      shops: [[first flag, item name, sold quantity]],  // 8-flag counters
      pairs: [[judge, flag, area or null]],      // tendency judge -> flag
    }

Use --stdout to emit only the replacement script block and --check to fail
when the page is out of date.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE / 'src'))
import des_flags  # noqa: E402

START = '/* FLAGDB:START (generated by tools/embed_flagdb.py; edit tools/build_flagdb.py) */'
END = '/* FLAGDB:END */'


def _js(value) -> str:
    # Escaping < prevents a description from terminating the inline script.
    return (json.dumps(value, ensure_ascii=False, separators=(',', ':'))
            .replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029'))


KIND_CODES = {"pickup": "p", "usage": "u"}
CATEGORY_CODES = {"Weapon": "W", "Armor": "A", "Ring": "R", "Goods": "G"}


def table(db: des_flags.FlagDB) -> dict:
    F = des_flags
    local = []
    for area in range(F.AREAS):
        rows = db.local.get(area + 1, {})
        local.append([[i, db.event_label(i, area) or '', KIND_CODES.get(rows[i].get('kind'), '')]
                      for i in db.documented_local(area)])
    scripts = [[i, ' | '.join(e.get('descs', [])[:3])] for i, e in sorted(db.scripts.items())
               if e.get('descs')]
    local_any = [[i, ' | '.join(e.get('descs', [])[:3])] for i, e in sorted(db.local_any.items())
                 if e.get('descs')]
    global_ids = set(db.globals) | set(db.shop_flags) | set(db.lot_flags) | set(db.npc_flags)
    global_ids |= {b['id'] for b in db.bosses} | {b['soul'] for b in db.bosses if b.get('soul')}
    capacity = F.BLOBS[F.PRIMARY][0]
    glob = [[i, db.event_label(i) or ''] for i in sorted(global_ids)
            if 0 <= i < capacity and not F.is_local(i)]
    glob = [row for row in glob if row[1]]
    return {
        "ranges": [list(r) for r in F.RANGES], "areas": F.AREAS,
        "backup": db.backup_offset,
        "areaNames": [db.area_name(a) for a in range(F.AREAS)],
        "bosses": [[b['id'], b['area'], b['name'], b['world'], b.get('soul'),
                    b.get('block', []), b.get('room', [])] for b in db.bosses],
        "npcs": [[n['list'], n.get('name', n['list']),
                  [[s['id'], s['name'], s.get('label', ''), 1 if s.get('marker') else 0]
                   for s in n['states']],
                  n.get('about', ''), n.get('where', '')] for n in db.npcs],
        "forgive": [[f['list'], f['id'],
                     [[int(a) - 1, flag] for a, flags in f.get('reset', {}).items() for flag in flags]]
                    for f in db.forgiveness],
        "local": local,
        "scripts": scripts,
        "localAny": local_any,
        "global": glob,
        "pickups": [[[flag, row['level'], [[CATEGORY_CODES.get(cat, '?'), item, count, name]
                                          for cat, item, count, name in row['items']]]
                     for flag, row in sorted(db.pickup_items.get(area, {}).items())]
                    for area in range(F.AREAS)],
        "shops": [[s['flag'], s.get('name') or str(s['item']), s.get('stock')]
                  for s in db.doc.get('shops', [])],
        "pairs": [[p['judge'], p['flag'], (p['area'] - 1) if 'area' in p else None]
                  for p in db.tendency_pairs],
    }


def block(db: des_flags.FlagDB | None) -> str:
    body = _js(table(db)) if db is not None else 'null'
    return START + '\nconst FLAGDB = ' + body + ';\n' + END


def embed(html: str, db: des_flags.FlagDB | None) -> str:
    if html.count(START) != 1 or html.count(END) != 1:
        raise ValueError('Could not locate one FLAGDB block')
    start, end = html.index(START), html.index(END) + len(END)
    return html[:start] + block(db) + html[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--html', type=Path, default=HERE / 'des_editor.html')
    parser.add_argument('--db', type=Path, default=HERE / 'flagdb.json')
    parser.add_argument('--stdout', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    db = des_flags.load_db(str(args.db))
    if db is None:
        print(f'{args.db} not found: run tools/build_flagdb.py first', file=sys.stderr)
        return 1
    if args.stdout:
        sys.stdout.write(block(db) + '\n')
        return 0
    html = args.html.read_text(encoding='utf-8')
    updated = embed(html, db)
    if args.check:
        if updated != html:
            print('des_editor.html event-flag table is out of date; run tools/embed_flagdb.py',
                  file=sys.stderr)
            return 1
        return 0
    args.html.write_text(updated, encoding='utf-8')
    print(f'Embedded {sum(len(a) for a in table(db)["local"])} local and '
          f'{len(table(db)["global"])} global flag labels', file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
